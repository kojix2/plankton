import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const operations = JSON.parse(await readFile(path.join(root, 'schema/operations.json'), 'utf8'));
const check = process.argv.includes('--check');
let crystal = '# Generated by scripts/generate.mjs from schema/operations.json. Do not edit.\nmodule Hydra\n';
for (const kind of ['source', 'texture']) {
    crystal += kind === 'source' ? '  module DSL\n' : '  class Texture\n';
    const selected = operations.filter((op) => kind === 'source' ? op.kind === 'source' : op.kind !== 'source');
    for (const op of selected) {
        const args = op.args.map((arg) => `${arg.name} : Scalar = ${Number.isInteger(arg.default) ? arg.default + '.0' : arg.default}`);
        if (op.kind === 'combine')
            args.unshift('other : Texture');
        const signature = args.length ? `(${args.join(', ')})` : '';
        const values = op.args.length ? `[${op.args.map((arg) => `Signal.cast(${arg.name})`).join(', ')}]` : '[] of Signal';
        const expression = op.kind === 'source' ? `Hydra.graph.add("${op.name}", ${values})`
            : op.kind === 'combine' ? `combine("${op.name}", other, ${values})` : `transform("${op.name}", ${values})`;
        crystal += `    # ${op.description}\n    def ${op.name}${signature} : Texture\n      ${expression}\n    end\n\n`;
    }
    crystal = crystal.trimEnd() + '\n  end\n\n';
}
crystal = crystal.trimEnd() + '\nend\n';
const js = '// Generated by scripts/generate.mjs. Do not edit.\nexport const OPERATIONS = Object.freeze(' + JSON.stringify(operations, null, 2) + ');\n';
for (const [name, contents] of [['src/hydra/generated.cr', crystal], ['web/js/operations.js', js]]) {
    const target = path.join(root, name);
    if (check) {
        if (await readFile(target, 'utf8') !== contents)
            throw new Error(`${name} is out of date. Run npm run generate.`);
    }
    else
        await writeFile(target, contents);
}
console.log(check ? 'Generated API files are current.' : `Generated ${operations.length} texture operations.`);
